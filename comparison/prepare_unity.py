"""Copy canonical benchmark/data and derive Unity's HUD font from the native source."""
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]

def prepare():
    assets = ROOT / "comparison/unity/Assets"
    (assets / "StreamingAssets").mkdir(parents=True, exist_ok=True)
    (assets / "Range").mkdir(parents=True, exist_ok=True)
    for path in (ROOT / "comparison/data").glob("*.json"):
        shutil.copyfile(path, assets / "StreamingAssets" / path.name)
    shutil.copyfile(ROOT / "tools/benchmark/unity/EventBenchmark.cs", assets / "Range/EventBenchmark.cs")
    source = (ROOT / "game/OverlayText.cpp").read_text(encoding="utf-8")
    glyphs = {name: [int(x.strip(), 0) for x in rows.split(",") if x.strip()]
              for name, rows in re.findall(r"static const Glyph (\w+)\s*=\s*\{\s*\{([^}]+)", source)}
    rows = []
    for char, name in re.findall(r"case '(.)':\s*return (\w+);", source):
        values = glyphs[name]
        assert len(values) == 7
        rows.append("            {'" + char + "',new int[]{" + ",".join(map(str, values)) + "}},")
    assert len(rows) > 10, "Native font format changed; inspect generator"
    text = "// Generated by comparison/prepare_unity.py. Edit OverlayText.cpp instead.\n"
    text += "using System.Collections.Generic;\nnamespace RangeComparison {\n    public static class FontRows {\n"
    text += "        public static readonly Dictionary<char,int[]> Rows=new Dictionary<char,int[]> {\n"
    text += "\n".join(rows) + "\n        };\n    }\n}\n"
    (assets / "Range/FontRows.cs").write_text(text, encoding="utf-8")
    print("Unity canonical data, metrics adapter and font prepared")

if __name__ == "__main__":
    prepare()
